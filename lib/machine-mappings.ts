// Articles and prepositions to keep lowercase (unless first word)
const lowercaseWords = new Set(['a', 'an', 'the', 'of', 'in', 'on', 'at', 'to', 'for', 'and', 'but', 'or', 'from', 'with'])

/**
 * Format a string to title case, keeping articles/prepositions lowercase
 * (except when they're the first word)
 */
function formatTitleCase(str: string): string {
  return str.split(' ').map((word, index) => {
    const lowerWord = word.toLowerCase()
    // Keep first word capitalized, others follow rules
    if (index === 0) {
      return word.charAt(0).toUpperCase() + word.slice(1)
    }
    // Keep articles/prepositions lowercase
    if (lowercaseWords.has(lowerWord)) {
      return lowerWord
    }
    // Capitalize other words
    return word.charAt(0).toUpperCase() + word.slice(1).toLowerCase()
  }).join(' ')
}

// Create a lowercase lookup map for case-insensitive matching
const dbToDisplayNameLower: Record<string, string> = Object.fromEntries(
  Object.entries(dbToDisplayName).map(([k, v]) => [k.toLowerCase(), v])
)

/**
 * Get the canonical machine key from ANY input format.
 * This is the authoritative normalization function - use it on ALL saves.
 *
 * This prevents future issues by always storing a consistent format.
 *
 * @param input - Any machine name format (display name, alias, key, etc.)
 * @returns The canonical key that should be stored in the database
 */
export function getCanonicalMachineKey(input: string): string {
  if (!input) return input

  const trimmed = input.trim()
  const lower = trimmed.toLowerCase()

  // Build a reverse lookup: longer display names → shorter keys
  // This helps us find "007" from "James Bond 007 (Thunderball/Dr No)"
  const displayToKey: Record<string, string> = {}
  const keySet = new Set<string>()

  for (const [alias, displayName] of Object.entries(machineMappings)) {
    const aliasLower = alias.toLowerCase().trim()
    const displayLower = displayName.toLowerCase().trim()

    // Identify likely keys: short (<=10 chars), no spaces, alphanumeric
    const aliasIsKey = alias.length <= 10 && !alias.includes(' ') && /^[a-zA-Z0-9_]+$/.test(alias)
    const displayIsKey = displayName.length <= 10 && !displayName.includes(' ') && /^[a-zA-Z0-9_]+$/.test(displayName)

    if (aliasIsKey) {
      keySet.add(alias)
      // Map display name to this key
      if (!displayToKey[displayLower] || alias.length < displayToKey[displayLower].length) {
        displayToKey[displayLower] = alias
      }
    }
    if (displayIsKey) {
      keySet.add(displayName)
    }

    // Also add the alias as a path to the key
    if (aliasIsKey) {
      displayToKey[aliasLower] = alias
    } else if (displayIsKey) {
      displayToKey[aliasLower] = displayName
    }
  }

  // Strategy 1: Input is already a known key
  if (keySet.has(trimmed) || keySet.has(trimmed.toUpperCase())) {
    return keySet.has(trimmed) ? trimmed : trimmed.toUpperCase()
  }

  // Strategy 2: Direct reverse lookup
  if (displayToKey[lower]) {
    return displayToKey[lower]
  }

  // Strategy 3: Input maps to something, then find the key for that
  const mapped = machineMappings[lower] || machineMappings[trimmed]
  if (mapped) {
    const mappedLower = mapped.toLowerCase().trim()
    // Check if mapped value is a key
    if (keySet.has(mapped)) {
      return mapped
    }
    // Check reverse lookup for the mapped value
    if (displayToKey[mappedLower]) {
      return displayToKey[mappedLower]
    }
    // If mapped looks like a key, return it
    if (mapped.length <= 10 && !mapped.includes(' ')) {
      return mapped.trim()
    }
  }

  // Strategy 4: Fuzzy match - check if input contains a known key's display name
  for (const [alias, displayName] of Object.entries(machineMappings)) {
    const displayLower = displayName.toLowerCase().trim()
    // If our input contains the display name, use the alias (if it's a key)
    if (lower.includes(displayLower) || displayLower.includes(lower)) {
      const aliasIsKey = alias.length <= 10 && !alias.includes(' ')
      if (aliasIsKey) {
        return alias
      }
    }
  }

  // Strategy 5: No mapping found - return trimmed original
  return trimmed
}

/**
 * Convert a database machine name to its display name with proper title case.
 * Falls back to formatting the input if no mapping exists.
 */
export function getMachineDisplayName(dbName: string): string {
  // Check direct mapping first (case-insensitive)
  const lowerName = dbName.toLowerCase()
  if (dbToDisplayNameLower[lowerName]) {
    return dbToDisplayNameLower[lowerName]
  }

  // Check if it's a camelCase or PascalCase name that needs splitting
  // e.g., "BlackKnight" -> "Black Knight"
  const spaced = dbName.replace(/([a-z])([A-Z])/g, '$1 $2')
  if (spaced !== dbName) {
    return formatTitleCase(spaced)
  }

  // If it's all caps and short (abbreviation), return as-is uppercase
  if (dbName.length <= 5 && /^[a-z0-9]+$/i.test(dbName)) {
    return dbName.toUpperCase()
  }

  // Otherwise just format what we have
  return formatTitleCase(dbName)
}
