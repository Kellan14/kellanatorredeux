// Extracts every collidable Surface from the RoboCop VPX. These include the
// elevated rail and overpass bodies that a ground-plane-only port misses.

import { writeFile } from 'node:fs/promises'
import { parseBiff, readCompoundFile, readGameItem } from './lib/vpx-reader.mjs'

const VPX_PATH = 'games/Robocop (Data East 1989)_drakkon(mod_1.2).vpx'
const OUTPUT_PATH = 'lib/vpx-robocop-walls.ts'

const streams = await readCompoundFile(VPX_PATH)
const gameData = parseBiff(streams.get('GameStg/GameData'))
const materialCount = gameData.find((record) => record.tag === 'MASI').data.readInt32LE(0)
const materialData = gameData.find((record) => record.tag === 'PHMA').data
const physicsMaterials = new Map()
for (let index = 0; index < materialCount; index += 1) {
  const offset = index * 48
  const name = materialData.subarray(offset, offset + 32).toString('latin1').replace(/\0.*$/, '').trim()
  physicsMaterials.set(name, {
    elasticity: materialData.readFloatLE(offset + 32),
    elasticityFalloff: materialData.readFloatLE(offset + 36),
    friction: materialData.readFloatLE(offset + 40),
    scatter: materialData.readFloatLE(offset + 44),
  })
}

const record = (item, tag) => item.records.find((candidate) => candidate.tag === tag)
const floatTag = (item, tag, fallback) => {
  const value = record(item, tag)
  return value?.data.length >= 4 ? value.data.readFloatLE(0) : fallback
}
const intTag = (item, tag, fallback = 0) => {
  const value = record(item, tag)
  return value?.data.length >= 4 ? value.data.readInt32LE(0) : fallback
}
const stringTag = (item, tag) => {
  const value = record(item, tag)
  if (!value || value.data.length < 4) return ''
  const length = value.data.readUInt32LE(0)
  if (length <= 0 || length + 4 > value.data.length) return ''
  return value.data.subarray(4, 4 + length).toString('latin1').replace(/\0+$/, '')
}
const rounded = (value) => Math.round(value * 100000) / 100000

function resolvePhysics(item) {
  const material = physicsMaterials.get(stringTag(item, 'MAPH'))
  if (material && !intTag(item, 'OVPH')) return material
  return {
    elasticity: floatTag(item, 'ELAS', 0.25),
    elasticityFalloff: floatTag(item, 'ELFO', 0),
    friction: floatTag(item, 'WFCT', 0.15),
    scatter: floatTag(item, 'WSCT', 0),
  }
}

function dragPoints(item) {
  const points = []
  for (let index = 0; index < item.records.length; index += 1) {
    if (item.records[index].tag !== 'DPNT') continue
    const center = item.records.slice(index + 1).find((candidate) => candidate.tag === 'VCEN')
    if (!center || center.data.length < 8) throw new Error(`${item.name} has a DPNT without VCEN`)
    points.push([rounded(center.data.readFloatLE(0)), rounded(center.data.readFloatLE(4))])
  }
  return points
}

const walls = [...streams.entries()]
  .filter(([key]) => /GameItem\d+$/.test(key))
  .map(([, value]) => readGameItem(value))
  .filter((item) => item.type === 0 && intTag(item, 'CLDW'))
  .map((item) => {
    const physics = resolvePhysics(item)
    const points = dragPoints(item)
    if (points.length < 3) throw new Error(`${item.name} has only ${points.length} drag points`)
    return {
      name: item.name,
      points,
      heightBottom: rounded(floatTag(item, 'HTBT', 0)),
      heightTop: rounded(floatTag(item, 'HTTP', 50)),
      solidBottom: Boolean(intTag(item, 'ISBS')),
      elasticity: rounded(physics.elasticity),
      elasticityFalloff: rounded(physics.elasticityFalloff),
      friction: rounded(physics.friction),
      scatter: rounded(physics.scatter),
    }
  })

const output = `// Generated by scripts/extract-vpx-collision-walls.mjs.\n`
  + `// Do not hand-edit: regenerate from the RoboCop VPX.\n\n`
  + `import type { VpxWall } from './vpx-robocop-table'\n\n`
  + `export type VpxCollisionWall = VpxWall & {\n`
  + `  heightBottom: number\n  heightTop: number\n  solidBottom: boolean\n}\n\n`
  + `export const VPX_COLLISION_WALLS = ${JSON.stringify(walls)} as const satisfies readonly VpxCollisionWall[]\n`

await writeFile(OUTPUT_PATH, output)
console.log(`wrote ${OUTPUT_PATH}: ${walls.length} collidable walls, ${walls.reduce((sum, wall) => sum + wall.points.length, 0)} points`)
