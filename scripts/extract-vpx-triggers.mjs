// Extracts every trigger volume from the RoboCop VPX. Triggers are not rigid
// bodies, but their exact custom polygons drive switches, ramp handoffs, and
// the table script's nFozzy flipper-polarity correction.

import { writeFile } from 'node:fs/promises'
import { readCompoundFile, readGameItem } from './lib/vpx-reader.mjs'

const VPX_PATH = 'games/Robocop (Data East 1989)_drakkon(mod_1.2).vpx'
const OUTPUT_PATH = 'lib/vpx-robocop-triggers.ts'

const streams = await readCompoundFile(VPX_PATH)
const record = (item, tag) => item.records.find((candidate) => candidate.tag === tag)
const floatTag = (item, tag, fallback = 0) => {
  const value = record(item, tag)
  return value?.data.length >= 4 ? value.data.readFloatLE(0) : fallback
}
const intTag = (item, tag, fallback = 0) => {
  const value = record(item, tag)
  return value?.data.length >= 4 ? value.data.readInt32LE(0) : fallback
}
const vector2Tag = (item, tag) => {
  const value = record(item, tag)
  return value?.data.length >= 8
    ? [value.data.readFloatLE(0), value.data.readFloatLE(4)]
    : [0, 0]
}
const rounded = (value) => Math.round(value * 100000) / 100000

function dragPoints(item) {
  const points = []
  const smooth = []
  for (let index = 0; index < item.records.length; index += 1) {
    if (item.records[index].tag !== 'DPNT') continue
    const pointRecords = []
    for (let nested = index + 1; nested < item.records.length; nested += 1) {
      pointRecords.push(item.records[nested])
      if (item.records[nested].tag === 'ENDB') break
    }
    const center = pointRecords.find((candidate) => candidate.tag === 'VCEN')
    if (!center || center.data.length < 8) throw new Error(`${item.name} has a DPNT without VCEN`)
    points.push([rounded(center.data.readFloatLE(0)), rounded(center.data.readFloatLE(4))])
    const smoothRecord = pointRecords.find((candidate) => candidate.tag === 'SMTH')
    smooth.push(Boolean(smoothRecord?.data.length >= 4 && smoothRecord.data.readInt32LE(0)))
  }
  return { points, smooth }
}

const triggers = [...streams.entries()]
  .filter(([key]) => /GameItem\d+$/.test(key))
  .map(([, value]) => readGameItem(value))
  .filter((item) => item.type === 6)
  .map((item) => {
    const { points, smooth } = dragPoints(item)
    return {
      name: item.name,
      center: vector2Tag(item, 'VCEN').map(rounded),
      radius: rounded(floatTag(item, 'RADI', 25)),
      hitHeight: rounded(floatTag(item, 'THOT', 50)),
      shape: intTag(item, 'SHAP'),
      enabled: Boolean(intTag(item, 'EBLD', 1)),
      points,
      smooth,
    }
  })

const output = `// Generated by scripts/extract-vpx-triggers.mjs.\n`
  + `// Do not hand-edit: regenerate from the RoboCop VPX.\n\n`
  + `export type VpxTriggerVolume = {\n`
  + `  name: string\n  center: readonly [number, number]\n  radius: number\n`
  + `  hitHeight: number\n  shape: number\n  enabled: boolean\n`
  + `  points: readonly (readonly [number, number])[]\n  smooth: readonly boolean[]\n}\n\n`
  + `export const VPX_TRIGGER_VOLUMES = ${JSON.stringify(triggers)} as const satisfies readonly VpxTriggerVolume[]\n`

await writeFile(OUTPUT_PATH, output)
console.log(`wrote ${OUTPUT_PATH}: ${triggers.length} trigger volumes, ${triggers.reduce((sum, trigger) => sum + trigger.points.length, 0)} points`)
