// Extracts VPX collections and their exact membership. Table scripts attach
// handlers to collections (for example dPosts_Hit), so object membership is
// part of the table's behavior rather than merely editor organization.

import { writeFile } from 'node:fs/promises'
import { parseBiff, readCompoundFile } from './lib/vpx-reader.mjs'

const VPX_PATH = 'games/Robocop (Data East 1989)_drakkon(mod_1.2).vpx'
const OUTPUT_PATH = 'lib/vpx-robocop-collections.ts'

const streams = await readCompoundFile(VPX_PATH)
const wideString = (record) => {
  if (!record || record.data.length < 4) return ''
  const byteLength = record.data.readUInt32LE(0)
  return record.data.subarray(4, 4 + byteLength).toString('utf16le').replace(/\0+$/, '')
}
const flag = (records, tag) => {
  const record = records.find((candidate) => candidate.tag === tag)
  return Boolean(record?.data.length >= 4 && record.data.readInt32LE(0))
}

const collections = [...streams.entries()]
  .filter(([key]) => /GameStg\/Collection\d+$/.test(key))
  .sort(([left], [right]) => Number(left.match(/\d+$/)[0]) - Number(right.match(/\d+$/)[0]))
  .map(([, value]) => {
    const records = parseBiff(value, 0, false)
    return {
      name: wideString(records.find((record) => record.tag === 'NAME')),
      items: records.filter((record) => record.tag === 'ITEM').map(wideString),
      fireEvents: flag(records, 'EVNT'),
      stopSingleEvents: flag(records, 'SSNG'),
      groupElements: flag(records, 'GREL'),
    }
  })

const output = `// Generated by scripts/extract-vpx-collections.mjs.\n`
  + `// Do not hand-edit: regenerate from the RoboCop VPX.\n\n`
  + `export type VpxCollection = {\n  name: string\n  items: readonly string[]\n`
  + `  fireEvents: boolean\n  stopSingleEvents: boolean\n  groupElements: boolean\n}\n\n`
  + `export const VPX_COLLECTIONS = ${JSON.stringify(collections)} as const satisfies readonly VpxCollection[]\n`

await writeFile(OUTPUT_PATH, output)
console.log(`wrote ${OUTPUT_PATH}: ${collections.length} collections, ${collections.reduce((sum, collection) => sum + collection.items.length, 0)} memberships`)
